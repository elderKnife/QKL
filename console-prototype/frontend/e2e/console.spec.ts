import { test, expect } from '@playwright/test'

// Integration against the actual local V2 services and their real FISCO evidence.
// The 40-round experiment is run explicitly before this suite; these tests never fake chain results.
async function login(page: any, role = 'grid') {
  await page.goto('/')
  if (await page.locator('#username').isVisible()) {
    await page.locator('#username').fill(role)
    await page.locator('#password').fill(role + '-local-password')
    await page.getByRole('button', { name: '进入实验控制台' }).click()
  }
  await expect(page.getByRole('heading', { name: '实验总览', exact: true })).toBeVisible()
}

