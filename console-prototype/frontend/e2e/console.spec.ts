test('manual GRID verification recomputes 12000 real original records', async ({ page }) => {
  await login(page)
  await page.getByRole('button', { name: /国网校验工作台/ }).click()
  const responsePromise = page.waitForResponse(r => /\/api\/v2\/grid\/groups\/.+\/verify$/.test(r.url()) && r.request().method() === 'POST')
  await page.getByRole('button', { name: '批量校验', exact: true }).first().click()
  const result = await (await responsePromise).json()
  expect(result.status).toBe('PASS')
  expect(result.batchCount).toBe(40)
  expect(result.recordCount).toBe(12000)
  expect(result.computedRootHash).toBe(result.chainRootHash)
  expect(result.rootsEqual).toBe(true)
  expect(result.comparisonNs).toBeGreaterThanOrEqual(0)
  expect(result.comparisonMs).toBe(result.comparisonNs / 1e6)
  expect(result.verificationMs).toBe(result.comparisonMs)
  expect(result.totalVerificationMs).toBeGreaterThan(result.verificationMs)
  expect(result.batchChecks).toHaveLength(40)
  await expect(page.getByRole('heading', { name: 'VPP-A · 12,000 条' })).toBeVisible()
  await expect(page.locator('.detail-list')).toContainText('ms')
  await expect(page.locator('.detail-list')).not.toContainText(/μs|微秒/)
  await expect(page.locator('.comparison-result')).toHaveText(/^\d+(\.\d+)? ms$/)
  expect(parseFloat(await page.locator('.comparison-result').innerText())).toBeCloseTo(result.comparisonNs / 1e6, 6)
  await page.screenshot({ path: 'test-results/v2-verification.png', fullPage: true })
})

